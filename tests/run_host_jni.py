#!/usr/bin/env python3
"""Optional Linux JNI smoke test, not Android/Kotlin/codec testing.

Usage: python3 tests/run_host_jni.py JAVA_HOME /absolute/libowncut_host.so
Needs a local JVM and JPype1. Generates an original tiny Java fixture class directly
(no Java compiler required); every native method uses the production class/symbol
name. Generated bytecode and test documents live only in a temporary directory.
"""
import json
from pathlib import Path
import struct
import sys
import tempfile
import uuid

BINDINGS = {
    'nativeCreate': '(Ljava/lang/String;)J',
    'nativeGetStatus': '(J)Ljava/lang/String;',
    'nativeGetRevision': '(J)Ljava/lang/String;',
    'nativeGetClipPage': '(JIILjava/lang/String;)Ljava/lang/String;',
    'nativeGetTimelineSnapshot': '(J)Ljava/lang/String;',
    'nativeGetMediaAssets': '(J)Ljava/lang/String;',
    'nativeResolvePlayhead': '(JLjava/lang/String;J)Ljava/lang/String;',
    'nativeAddMediaClip': '(JLjava/lang/String;J)Ljava/lang/String;',
    'nativeRelinkClipMedia': '(JLjava/lang/String;Ljava/lang/String;)V',
    'nativeMoveClip': '(JLjava/lang/String;Ljava/lang/String;J)V',
    'nativeSplitClip': '(JLjava/lang/String;JLjava/lang/String;)V',
    'nativeTrimClip': '(JLjava/lang/String;ZJ)V',
    'nativeDeleteClip': '(JLjava/lang/String;Z)V',
    'nativeUndo': '(J)Z', 'nativeRedo': '(J)Z', 'nativeDestroy': '(J)V',
    **{name: '(JLjava/lang/String;)V' for name in (
        'nativeSaveProject', 'nativeLoadProject', 'nativeSaveAutosave',
        'nativeClearAutosave', 'nativeSaveCopy', 'nativeRestoreDraft', 'nativeCheckpointProject')},
    'nativeLoadAutosave': '(JLjava/lang/String;)Z',
    'nativeRepairCheckpoint': '(JLjava/lang/String;)Z',
}

def fixture_class():
    pool = [b'']
    def add(value): pool.append(value); return len(pool)-1
    def u16(value): return struct.pack('>H', value)
    def utf(value):
        data = value.encode('ascii')
        return add(b'\x01'+u16(len(data))+data)
    def cls(name): return add(b'\x07'+u16(utf(name)))
    def method(owner, name, signature):
        pair = add(b'\x0c'+u16(utf(name))+u16(utf(signature)))
        return add(b'\x0a'+u16(owner)+u16(pair))
    own = cls('com/owncut/app/EngineSession'); parent = cls('java/lang/Object')
    constructor = method(parent, '<init>', '()V')
    load = method(cls('java/lang/System'), 'load', '(Ljava/lang/String;)V')
    code_name = utf('Code')
    def code_method(name, signature, flags, code):
        body = struct.pack('>HHI', 1, 1, len(code))+code+u16(0)+u16(0)
        return (struct.pack('>HHHH', flags, utf(name), utf(signature), 1)
                +u16(code_name)+struct.pack('>I', len(body))+body)
    methods = [code_method('<init>', '()V', 1, b'\x2a\xb7'+u16(constructor)+b'\xb1'),
               code_method('load', '(Ljava/lang/String;)V', 9, b'\x2a\xb8'+u16(load)+b'\xb1')]
    methods += [struct.pack('>HHHH', 0x101, utf(name), utf(signature), 0)
                for name, signature in BINDINGS.items()]
    return (struct.pack('>IHHH', 0xcafebabe, 0, 52, len(pool))+b''.join(pool[1:])
            +struct.pack('>HHHHHH', 0x31, own, parent, 0, 0, len(methods))
            +b''.join(methods)+u16(0))

def check(value):
    if not value: raise AssertionError('host JNI contract failed')

def main():
    import jpype
    java_home, library = map(Path, sys.argv[1:])
    with tempfile.TemporaryDirectory(prefix='owncut-jni-') as temporary:
        root = Path(temporary)
        fixture = root/'com/owncut/app/EngineSession.class'
        fixture.parent.mkdir(parents=True); fixture.write_bytes(fixture_class())
        jpype.startJVM(str(java_home/'lib/server/libjvm.so'), '-Xcheck:jni',
                      '--enable-native-access=ALL-UNNAMED', classpath=[str(root)], convertStrings=True)
        try:
            engine_class = jpype.JClass('com.owncut.app.EngineSession')
            engine_class.load(str(library.resolve()))
            engine = engine_class()
            ids = [str(uuid.uuid4()), str(uuid.uuid4())]
            handles = [engine.nativeCreate(identity) for identity in ids]
            def failure(operation):
                try: operation()
                except jpype.JClass('java.lang.IllegalArgumentException'): return
                raise AssertionError('expected Java IllegalArgumentException')
            try:
                first, second = handles
                uri = 'content://বাংলা/🎬?name="quoted"\\source'
                clip = engine.nativeAddMediaClip(first, uri, 4000)
                engine.nativeSplitClip(first, clip, 60, 'right-🎬')
                check(json.loads(engine.nativeGetTimelineSnapshot(first))['clips'][1]['id'] == 'right-🎬')
                assets = json.loads(engine.nativeGetMediaAssets(first))['assets']
                check(len(assets) == 1 and assets[0]['mediaId'] == uri and len(assets[0]['clipIds']) == 2)
                check(assets[0]['requiredSourceEndMs'] == 4000)
                check(json.loads(engine.nativeGetTimelineSnapshot(second))['clips'] == [])
                primary = root/'বাংলা🎬.owncut'
                engine.nativeCheckpointProject(first, str(primary))
                check((root/'বাংলা🎬.owncut.checkpoint').read_bytes()[28] == 2)
                check(not Path(str(primary)+'.autosave').exists())
                length = struct.unpack_from('<I', primary.read_bytes(), 12)[0]
                check(primary.read_bytes()[16:16+length].decode() == ids[0])
                engine.nativeLoadProject(second, str(primary))
                engine.nativeRelinkClipMedia(second, clip, 'content://new/🎬')
                check(engine.nativeUndo(second)); check(engine.nativeRedo(second))
                failure(lambda: engine.nativeAddMediaClip(second, 'nul\0source', 1000))
                invalid = jpype.JClass('java.lang.String')(jpype.JArray(jpype.JChar)([0xd800]))
                failure(lambda: engine.nativeAddMediaClip(second, invalid, 1000))
                # Exception messages may themselves contain non-BMP filesystem paths.
                directory = root/'directory-🎬'; directory.mkdir()
                try: engine.nativeSaveCopy(first, str(directory))
                except jpype.JClass('java.lang.IllegalArgumentException') as error: check('🎬' in str(error))
                else: raise AssertionError('rename to directory should fail')
                journal = Path(str(primary)+'.checkpoint'); journal.write_text('damaged')
                failure(lambda: engine.nativeCheckpointProject(first, str(primary)))
                check(Path(str(primary)+'.autosave').exists())
                before = primary.read_bytes()
                check(engine.nativeRepairCheckpoint(first, str(primary)))
                check(primary.read_bytes() == before)
                engine.nativeCheckpointProject(first, str(primary))
                for index in range(270): engine.nativeAddMediaClip(second, 'content://batch/'+str(index), 1000)
                all_clips = json.loads(engine.nativeGetTimelineSnapshot(second))['clips']
                check(len(all_clips) == 272)
                page = json.loads(engine.nativeGetClipPage(second, 0, 256, None))
                revision = page['revision']
                check(isinstance(revision, str) and revision == engine.nativeGetRevision(second))
                check(page['total'] == 272 and page['nextOffset'] == 256)
                last = json.loads(engine.nativeGetClipPage(second, 256, 256, revision))
                check(page['clips'] + last['clips'] == all_clips and last['nextOffset'] == 272)
                check(json.loads(engine.nativeGetClipPage(second,272,1,revision))['clips'] == [])
                for offset,limit,expected in [(-1,1,None),(273,1,None),(0,0,None),(0,257,None),
                    (0,1,''),(0,1,'-1'),(0,1,'1x'),(0,1,'18446744073709551616')]:
                    failure(lambda: engine.nativeGetClipPage(second,offset,limit,expected))
                engine.nativeAddMediaClip(second,'content://changed',1000)
                failure(lambda: engine.nativeGetClipPage(second,256,256,revision))
                # Destroy races must never dereference a freed address; close is idempotent.
                from concurrent.futures import ThreadPoolExecutor
                temporary = engine.nativeCreate(str(uuid.uuid4()))
                def read_or_closed(_):
                    for i in range(80):
                        try: engine.nativeGetClipPage(temporary,0,1,None)
                        except jpype.JClass('java.lang.IllegalArgumentException'): pass
                with ThreadPoolExecutor(max_workers=4) as pool:
                    jobs = [pool.submit(read_or_closed,i) for i in range(4)]
                    engine.nativeDestroy(temporary)
                    for job in jobs: job.result()
                engine.nativeDestroy(temporary)
                failure(lambda: engine.nativeGetStatus(temporary))
                failure(lambda: engine.nativeGetStatus(0))
                failure(lambda: engine.nativeGetStatus(-1))
                failure(lambda: engine.nativeGetStatus(9223372036854775807))
                replacement = engine.nativeCreate(str(uuid.uuid4()))
                check(replacement > temporary)
                engine.nativeDestroy(replacement)
                print('Host JVM JNI: Unicode, revision pages, stale/invalid handles, concurrent destroy, catalog and recovery passed')
            finally:
                for handle in handles: engine.nativeDestroy(handle)
        finally: jpype.shutdownJVM()

if __name__ == '__main__': main()
